"""Builds static/js/icons.js from Phosphor Icons (MIT, https://phosphoricons.com).

Usage:  npm pack @phosphor-icons/core && tar xzf phosphor-icons-core-*.tgz
        python3 scripts/build_icons.py package          # folder that holds assets/
Only the icons listed below are embedded (the whole set is 1,500 icons). "name" = light weight,
"name:fill" / "name:duotone" = other weights. Add a name here and rerun to use a new icon.
"""
import re
import sys
from pathlib import Path

ICONS = """
check x arrow-right arrow-up arrow-down caret-down plus drop magnifying-glass trophy fire sparkle fork-knife bell target scales
chart-line-up clock-counter-clockwise barbell camera chart-bar note-pencil star star:fill clock microphone lock question smiley-meh
bowl-food cooking-pot prohibit check-circle calendar-blank device-mobile keyboard download-simple ruler palette speaker-high
speaker-low chat-circle-dots key file-text lightning crown-simple leaf medal sun moon person-simple-run:duotone person-simple-run brain:duotone
person-simple-walk person-simple-hike person-simple-bike bicycle person-simple-swim person-simple-tai-chi flower-lotus person-arms-spread hand-fist
soccer-ball basketball tennis-ball volleyball boxing-glove boat broom plant stairs music-notes music-notes-simple sneaker sneaker-move
speedometer heartbeat baby-carriage mountains timer grains heart house user
""".split()

root = Path(sys.argv[1]) / "assets"
out = {}
for spec in ICONS:
    name, _, weight = spec.partition(":")
    weight = weight or "light"
    svg = (root / weight / f"{name}-{weight}.svg").read_text()
    out[spec] = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()

body = ",\n".join(f"  {spec!r}: {markup!r}".replace("\\'", "'") for spec, markup in out.items())
target = Path(__file__).resolve().parent.parent / "static" / "js" / "icons.js"
target.write_text(HEADER := """// Icons: Phosphor Icons (MIT, (c) 2023 Phosphor Icons), only the ones cadence uses. Generated by scripts/build_icons.py - do not edit by hand.
// Use <i data-ico="drop"></i> in HTML (filled in automatically, also in anything added later) or cadenceIcons.icon('drop') in a template string.
(function () {
  const PATHS = {
""" + body + """
  };
  function icon(name, extra) {
    const markup = PATHS[name] || PATHS[`${name}:fill`] || '';
    return `<svg class="ph${extra ? ` ${extra}` : ''}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" focusable="false">${markup}</svg>`;
  }
  function hydrate(root) {
    (root || document).querySelectorAll('i[data-ico]:empty').forEach((el) => { el.innerHTML = icon(el.dataset.ico); });
  }
  // Standalone svg with its own size and colour (for drawings that are not text, like the award hexagons).
  function svg(name, size, color) {
    const markup = PATHS[name] || '';
    return `<svg width="${size}" height="${size}" viewBox="0 0 256 256" fill="${color || 'currentColor'}" aria-hidden="true" focusable="false">${markup}</svg>`;
  }
  window.cadenceIcons = { icon, svg, hydrate, has: (name) => name in PATHS };
  window.ico = icon;
  const start = () => {
    hydrate();
    new MutationObserver(() => hydrate()).observe(document.documentElement, { childList: true, subtree: true });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
""")
print("icons:", len(out), "bytes:", target.stat().st_size)
